BEGIN;

CREATE TABLE IF NOT EXISTS waste_listings (
    listing_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demo_key text UNIQUE,
    material_type text NOT NULL,
    estimated_weight_kg numeric(10, 2) NOT NULL CHECK (estimated_weight_kg > 0)
);

CREATE TABLE IF NOT EXISTS collectors (
    collector_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demo_key text UNIQUE,
    name text NOT NULL
);

CREATE TABLE IF NOT EXISTS offers (
    offer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id integer NOT NULL REFERENCES waste_listings (listing_id),
    collector_id integer NOT NULL REFERENCES collectors (collector_id),
    proposed_price numeric(12, 2) NOT NULL CHECK (proposed_price > 0),
    pickup_fee numeric(12, 2) NOT NULL CHECK (pickup_fee BETWEEN 0 AND proposed_price),
    pickup_schedule timestamptz NOT NULL,
    status text NOT NULL DEFAULT 'Pending'
);

COMMIT;
